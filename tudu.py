import sys
from list_tasks import list_tasks
from add_task import add_task
from done_task import done_task
import AUTOGENERATED_VERSION

print("sys.argv: ",sys.argv)

# Проверяем, что нам передали команду
if len(sys.argv) < 2:
    print("Используйте: add, list, listdone или done")
    sys.exit()

command = sys.argv[1].lower()

# --- ДОБАВИТЬ ЗАДАЧУ ---
if command == "add":
    add_task(sys.argv[2:])

# --- ПОКАЗАТЬ СПИСОК С ВЫПОЛНЕННЫМИ---
if command == "listdone":
    show_all = True
    list_tasks(show_all)

# --- ПОКАЗАТЬ СПИСОК БЕЗ ВЫПОЛНЕННЫХ---
if command == "list":
    show_all = False
    list_tasks(show_all)


# --- ВЫПОЛНИТЬ ПО НОМЕРУ ---
if command == "done":
    if len(sys.argv) > 2:
        done_task(sys.argv[2])
    else:
        done_task()

if command == "--version":
    print("Версия программы: ", AUTOGENERATED_VERSION.__version__)
