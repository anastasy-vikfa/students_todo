import subprocess
import os

def get_git_version():
    try:
        # Выполняем команду git describe
        version = subprocess.check_output(
            ["git", "describe", "--tags", "--always"],
            stderr=subprocess.STDOUT,
            text=True,
        ).strip()
        return version
    except subprocess.CalledProcessError:
        return "Ошибка: папка не является git-репозиторием"
    except FileNotFoundError:
        return "Ошибка: git не установлен в системе"


if __name__ == "__main__":
    print(f"Версия проекта: {get_git_version()}")


# Записываем код в файл с кодировкой UTF-8
with open("AUTOGENERATED_VERSION.py", "w", encoding="utf-8") as file:
    file.write(f"__version__ = \"{get_git_version()}\"")
